#!/usr/bin/env bash
# Wired DHCP networking for QEMU, Hyper-V, and physical machines.
set -uo pipefail
set +h
export LFS=/ KRYPTOS_ROOT=/root/kryptos
source /root/kryptos/lib/build.sh

b_dhcpcd() {
    printf '%s  %s\n' \
        5f257b02f874b3b8cb031e5be79c99cf9cbd4f65eae2a50c9b1beddafb3f51bc \
        /sources/dhcpcd-10.2.2.tar.xz | sha256sum -c -
    getent group dhcpcd >/dev/null || groupadd --system dhcpcd
    id dhcpcd >/dev/null 2>&1 || useradd --system -g dhcpcd \
        -d /var/lib/dhcpcd -s /bin/false -c 'DHCP privilege separation' dhcpcd
    install -d -m700 -o dhcpcd -g dhcpcd /var/lib/dhcpcd
    into dhcpcd-10.2.2
    ./configure --prefix=/usr --sysconfdir=/etc --libexecdir=/usr/lib/dhcpcd \
        --dbdir=/var/lib/dhcpcd --runstatedir=/run --privsepuser=dhcpcd
    make
    make test
    make install
    /usr/sbin/dhcpcd --version
}

b_network_dhcp() {
    # Migrate only our exact old QEMU config. Preserve custom static configs.
    if [ -f /etc/sysconfig/ifconfig.eth0 ] && cmp -s /etc/sysconfig/ifconfig.eth0 <(cat <<'OLD'
ONBOOT=yes
IFACE=eth0
SERVICE=ipv4-static
IP=10.0.2.15
GATEWAY=10.0.2.2
PREFIX=24
BROADCAST=10.0.2.255
OLD
    ); then
        mv /etc/sysconfig/ifconfig.eth0 /etc/sysconfig/kryptos-qemu-static.bak
    fi
    # Remove only the resolver generated by the old QEMU recipe.
    if [ -f /etc/resolv.conf ] && cmp -s /etc/resolv.conf <(printf 'nameserver 1.1.1.1\nnameserver 8.8.8.8\n'); then
        cp -p /etc/resolv.conf /etc/sysconfig/kryptos-resolv.bak
        printf '# Populated by dhcpcd after a lease is acquired.\n' > /etc/resolv.conf
    fi
    [ ! -f /etc/dhcpcd.conf ] || cp -p /etc/dhcpcd.conf /etc/dhcpcd.conf.pre-kryptos
    cat > /etc/dhcpcd.conf <<'CONF'
# Wired DHCP only. Wi-Fi authentication is a separate future component.
hostname
clientid
persistent
option domain_name_servers, domain_name, domain_search
option classless_static_routes
option interface_mtu
require dhcp_server_identifier
nohook hostname
allowinterfaces eth* en*
CONF
    install -m755 /root/kryptos/config/kryptos-network /etc/rc.d/init.d/kryptos-network
    for level in 2 3 4 5; do
        install -d "/etc/rc.d/rc$level.d"
        ln -sf ../init.d/kryptos-network "/etc/rc.d/rc$level.d/S21kryptos-network"
    done
    for level in 0 1 6; do
        install -d "/etc/rc.d/rc$level.d"
        ln -sf ../init.d/kryptos-network "/etc/rc.d/rc$level.d/K79kryptos-network"
    done
    # Do not start a network daemon inside the build chroot.
}
msg "wired DHCP: automatic interfaces, routes, and DNS"
step network_dhcpcd_10_2_2 b_dhcpcd
step network_dhcp_config_v1 b_network_dhcp
msg "DHCP installed; rebuild ISO and verify a real lease after boot."
